// Picks a real board position for each technique, for the diagrams in the technique guide.
// The engine finds them in banked puzzles, so every diagram is a genuine, correct example.
// Usage: node tools/make-guide-examples.js
const fs = require('fs');
const path = require('path');
const E = require('../engine/engine.js');
const bank = require('../src/bank.json');

// Techniques about one digit read best with only that digit's candidates drawn.
const ONE_DIGIT = new Set(['x_wing', 'skyscraper', 'two_string_kite', 'swordfish', 'turbot_fish', 'simple_colouring', 'x_chain']);
const IN_UNIT = new Set(['full_house', 'hidden_single_box', 'hidden_single_line', 'naked_single', 'pointing', 'claiming', 'naked_pair', 'hidden_pair', 'naked_triple', 'hidden_triple']);

const best = {};
for (let l = 1; l <= 10; l++) for (const s of bank[l]) {
  E.grade(E.parse(s), (step, v, c) => {
    const id = step.tech.id, filled = Array.from(v).filter(x => x).length;
    if (step.place && filled > 60) return; // late-game singles make dull pictures
    const size = step.cells.length * 3 + step.elims.length + (IN_UNIT.has(id) ? 0 : Math.abs(2 - step.elims.length));
    if (best[id] && best[id].size <= size) return;
    const show = new Set(step.cells.concat(step.elims.map(e => e.cell)));
    if (IN_UNIT.has(id)) for (const i of step.region) show.add(i);
    best[id] = {
      size, vals: E.format(v), cand: Array.from(c), cells: step.cells, elims: step.elims.map(e => [e.cell, e.digit]),
      place: step.place ? [step.place.cell, step.place.digit] : null, where: step.where,
      show: [...show], digit: ONE_DIGIT.has(id) ? step.digits[0] : 0,
    };
  });
}
const missing = E.TECHS.filter(t => !best[t.id]).map(t => t.id);
if (missing.length) { console.log('no example found for: ' + missing.join(', ')); process.exit(1); }
for (const id in best) delete best[id].size;
const out = path.join(__dirname, '..', 'src', 'guide-examples.js');
fs.writeFileSync(out, '// Generated by tools/make-guide-examples.js. Do not edit by hand.\nself.SUDOKU_GUIDE_EXAMPLES = ' + JSON.stringify(best) + ';\n');
console.log(`wrote ${Object.keys(best).length} examples to ${out} (${(fs.statSync(out).size / 1024).toFixed(0)} KB)`);
